// Function to get random word pair
export const getRandomWordPair = () => {
  const randomIndex = Math.floor(Math.random() * wordPairs.length)
  return wordPairs[randomIndex]
}

// Function to get multiple unique word pairs (untuk multiple rounds nanti kalau perlu)
export const getMultipleWordPairs = (count) => {
  const shuffled = [...wordPairs].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, count)
}

